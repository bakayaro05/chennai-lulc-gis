// ======================================================
// 12. SPECTRAL INDEX FUNCTION
// ======================================================
//
// IMPORTANT:
//
// Explicit arithmetic is used instead of
// normalizedDifference().
//
// This avoids unnecessary masking when scaled surface
// reflectance contains legitimate negative values.
//
// NDVI:
// (NIR - RED) / (NIR + RED)
//
// NDWI:
// (GREEN - NIR) / (GREEN + NIR)
//
// NDBI:
// (SWIR1 - NIR) / (SWIR1 + NIR)
//
// ======================================================

function addIndices(image) {

  var nir = image.select('nir');

  var red = image.select('red');

  var green = image.select('green');

  var swir1 = image.select('swir1');


  // ----------------------------------------------------
  // NDVI
  // ----------------------------------------------------

  var ndvi = nir

    .subtract(red)

    .divide(
      nir.add(red)
    )

    .rename('NDVI');


  // ----------------------------------------------------
  // NDWI
  // ----------------------------------------------------

  var ndwi = green

    .subtract(nir)

    .divide(
      green.add(nir)
    )

    .rename('NDWI');


  // ----------------------------------------------------
  // NDBI
  // ----------------------------------------------------

  var ndbi = swir1

    .subtract(nir)

    .divide(
      swir1.add(nir)
    )

    .rename('NDBI');


  return image.addBands([
    ndvi,
    ndwi,
    ndbi
  ]);

}



