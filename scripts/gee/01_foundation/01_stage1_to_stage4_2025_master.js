// FUNCTION: CHECK VALUES OUTSIDE -1 TO +1
// ======================================================

function printExtremeIndexPct(yearLabel, stack) {

  var indices = stack.select([
    'NDVI',
    'NDWI',
    'NDBI'
  ]);


  function extremePct(bandName) {

    var band = indices.select(bandName);

    var extreme = band
      .lt(-1)
      .or(
        band.gt(1)
      )
      .rename('extreme');


    var fraction = extreme.reduceRegion({

      reducer: ee.Reducer.mean(),

      geometry: chennaiROI,

      scale: 30,

      maxPixels: 1e9,

      tileScale: 4

    }).get('extreme');


    return ee.Number(fraction)
      .multiply(100);
  }


  print(

    ee.String(yearLabel)

      .cat(' values outside [-1,1] | NDVI=')

      .cat(
        extremePct('NDVI')
          .format('%.6f')
      )

      .cat('% | NDWI=')

      .cat(
        extremePct('NDWI')
          .format('%.6f')
      )

      .cat('% | NDBI=')

      .cat(
        extremePct('NDBI')
          .format('%.6f')
      )

      .cat('%')

  );
}



