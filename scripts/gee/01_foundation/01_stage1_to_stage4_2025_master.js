//
// stack2025
// mlcStatsBuiltup2025
// mlcStatsVegetation2025
// mlcStatsWater2025
// mlcStatsAgriOpen2025
// mlcStatsBarrenFallow2025
//
// Predictor order:
//
// blue
// green
// red
// nir
// swir1
// swir2
// NDVI
// NDWI
// NDBI
//
// Classification formula:
//
// g_c(x) =
//
//   -0.5 * ln(|Sigma_c|)
//   -0.5 * (x - mu_c)' Sigma_c^-1 (x - mu_c)
//
// Equal class priors are used.
//
// The common Gaussian constant:
//
// -(p/2) * ln(2*pi)
//
// is omitted because it is identical for all classes
// and therefore does not affect which class has the
// maximum likelihood.
//
// ======================================================


// ======================================================
// 1. CREATE 9 x 1 PIXEL VECTOR IMAGE
// ======================================================
//
// stack2025.select(MLC_BANDS)
//
// becomes:
//
// [blue]
// [green]
// [red]
// [nir]
// [swir1]
// [swir2]
// [NDVI]
// [NDWI]
// [NDBI]
//
// for every pixel.
//
// ======================================================

var mlcPixelVector2025 =
  stack2025
    .select(
      MLC_BANDS
    )
    .toArray()
    .toArray(
      1
    );


// ======================================================
// 2. FUNCTION:
// CALCULATE GAUSSIAN MLC SCORE FOR ONE CLASS
// ======================================================

function createMLCScoreImage(
  statsDictionary,
  classId,
  outputName
) {

  var stats =
    ee.Dictionary(
      statsDictionary
    );


  // ----------------------------------------------------
  // CLASS MEAN
  //
  // Stored Stage 4A shape:
  //
  // 1 x 9
  //
  // Convert to:
  //
  // 9 x 1
  //
  // ----------------------------------------------------

  var meanVector =
    ee.Array(
      stats.get(
        'mean'
      )
    )
    .matrixTranspose();


  // ----------------------------------------------------
  // REGULARIZED INVERSE COVARIANCE MATRIX
  //
  // Shape:
  //
  // 9 x 9
  //
  // ----------------------------------------------------

  var inverseCovariance =
    ee.Array(
      stats.get(
        'inverse_covariance'
      )
    );


  // ----------------------------------------------------
  // REGULARIZED DETERMINANT
  // ----------------------------------------------------

  var determinant =
    ee.Number(
      stats.get(
        'regularized_determinant'
      )
    );


  // ----------------------------------------------------
  // CONVERT CONSTANT ARRAYS TO ARRAY IMAGES
  // ----------------------------------------------------

  var meanImage =
    ee.Image(
      meanVector
    );


  var inverseCovarianceImage =
    ee.Image(
      inverseCovariance
    );


  // ----------------------------------------------------
  // DIFFERENCE VECTOR
  //
  // d = x - mu
  //
  // Shape:
  //
  // 9 x 1
  //
  // ----------------------------------------------------

  var difference =
    mlcPixelVector2025.subtract(
      meanImage
    );


  // ----------------------------------------------------
  // MAHALANOBIS TERM
  //
  // d' Sigma^-1 d
  //
  //
  // Shapes:
  //
  // d'          = 1 x 9
  // Sigma^-1    = 9 x 9
  // d           = 9 x 1
  //
  // result      = 1 x 1
  //
  // ----------------------------------------------------

  var mahalanobisArray =
    difference

      .matrixTranspose()

      .matrixMultiply(
        inverseCovarianceImage
      )

      .matrixMultiply(
        difference
      );


  // ----------------------------------------------------
  // CONVERT 1 x 1 ARRAY TO NORMAL SCALAR IMAGE
  // ----------------------------------------------------

  var mahalanobis =
    mahalanobisArray
      .arrayGet(
        [
          0,
          0
        ]
      );


  // ----------------------------------------------------
  // LOG DETERMINANT
  // ----------------------------------------------------

  var logDeterminant =
    determinant.log();


  // ----------------------------------------------------
  // GAUSSIAN LOG-LIKELIHOOD SCORE
  //
  // score =
  //
  // -0.5 ln(|Sigma|)
  // -0.5 MahalanobisDistance
  //
  // ----------------------------------------------------

  var score =
    mahalanobis

      .multiply(
        -0.5
      )

      .subtract(
        ee.Image.constant(
          logDeterminant.multiply(
            0.5
          )
        )
      )

      .rename(
        outputName
      );


  return score;

}


