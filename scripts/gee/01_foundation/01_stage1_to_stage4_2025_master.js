// 10. CLEAR OBSERVATION SUMMARY
// ======================================================

function printCountSummary(yearLabel, countImage) {

  var filledCount = countImage
    .unmask(0);


  var countStats = filledCount.reduceRegion({

    reducer:

      ee.Reducer.minMax()

      .combine({
        reducer2: ee.Reducer.median(),
        sharedInputs: true
      }),

    geometry: chennaiROI,

    scale: 30,

    maxPixels: 1e9,

    tileScale: 4

  });


  var minimum = ee.Number(
    countStats.get('clear_count_min')
  );


  var median = ee.Number(
    countStats.get('clear_count_median')
  );


  var maximum = ee.Number(
    countStats.get('clear_count_max')
  );


  var zeroImage = filledCount

    .eq(0)

    .rename('zero');


  var zeroFraction = ee.Number(

    zeroImage.reduceRegion({

      reducer: ee.Reducer.mean(),

      geometry: chennaiROI,

      scale: 30,

      maxPixels: 1e9,

      tileScale: 4

    })

    .get('zero')

  );


  var zeroPercent = zeroFraction
    .multiply(100);


  print(

    ee.String(yearLabel)

      .cat(' clear observations | min=')

      .cat(
        minimum.format('%.0f')
      )

      .cat(' | median=')

      .cat(
        median.format('%.0f')
      )

      .cat(' | max=')

      .cat(
        maximum.format('%.0f')
      )

      .cat(' | zero-coverage=')

      .cat(
        zeroPercent.format('%.4f')
      )

      .cat('%')

  );

}



