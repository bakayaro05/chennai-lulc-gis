// ======================================================
// STAGE 4A
// GAUSSIAN MAXIMUM LIKELIHOOD CLASSIFICATION
// CLASS STATISTICS + COVARIANCE MATRIX QA
// ======================================================
//
// INPUT:
//
// finalTraining2025
//
// 600 balanced training pixels
// 120 pixels per class
//
// Predictor bands:
//
// blue
// green
// red
// nir
// swir1
// swir2
// NDVI
// NDWI
// NDBI
//
// PURPOSE:
//
// For each LULC class:
//
// 1. Build training data matrix
// 2. Calculate 9-variable mean vector
// 3. Calculate 9 x 9 covariance matrix
// 4. Calculate determinant
// 5. Add very small diagonal regularization
// 6. Check regularized determinant
// 7. Verify covariance matrix can be inverted
//
// NO CLASSIFICATION IS DONE YET.
//
// ======================================================


// ======================================================
// 1. MLC SETTINGS
// ======================================================

var MLC_BANDS = [
  'blue',
  'green',
  'red',
  'nir',
  'swir1',
  'swir2',
  'NDVI',
  'NDWI',
  'NDBI'
];


var MLC_BAND_COUNT =
  MLC_BANDS.length;


// ------------------------------------------------------
// SMALL COVARIANCE REGULARIZATION
// ------------------------------------------------------
//
// Some predictors are naturally correlated.
//
// Example:
//
// red / nir / NDVI
// nir / swir1 / NDBI
//
// A very small value is therefore added to the
// covariance diagonal before inversion.
//
// This does NOT change the class labels.
//
// It simply improves numerical stability.
//
// ======================================================

var MLC_REGULARIZATION =
  1e-6;


// ======================================================
// 2. FUNCTION:
// CONVERT ONE CLASS FEATURECOLLECTION TO MATRIX
// ======================================================
//
// Output matrix:
//
// rows    = training pixels
// columns = 9 predictors
//
// Example shape:
//
// 120 x 9
//
// ======================================================

function featureCollectionToMatrix(
  featureCollection
) {

  var sampleCount =
    featureCollection.size();


  var featureList =
    featureCollection.toList(
      sampleCount
    );


  var rows =
    featureList.map(
      function(item) {

        var feature =
          ee.Feature(
            item
          );


        var row =
          ee.List(
            MLC_BANDS
          ).map(
            function(bandName) {

              return feature.get(
                ee.String(
                  bandName
                )
              );

            }
          );


        return row;

      }
    );


  return ee.Array(
    rows
  );

}


// ======================================================
// 3. FUNCTION:
// CALCULATE MLC STATISTICS FOR ONE CLASS
// ======================================================

function calculateMLCClassStatistics(
  classId,
  className
) {

  // ----------------------------------------------------
  // FILTER CLASS
  // ----------------------------------------------------

  var classSamples =
    finalTraining2025.filter(
      ee.Filter.eq(
        'class_id',
        classId
      )
    );


  var n =
    classSamples.size();


  // ----------------------------------------------------
  // BUILD N x 9 DATA MATRIX
  // ----------------------------------------------------

  var X =
    featureCollectionToMatrix(
      classSamples
    );


  // ----------------------------------------------------
  // CALCULATE 1 x 9 MEAN VECTOR
  // ----------------------------------------------------

  var meanVector =
    X.reduce(
      ee.Reducer.mean(),
      [0]
    );


  // ----------------------------------------------------
  // REPEAT MEAN VECTOR TO N x 9
  // ----------------------------------------------------

  var repeatedMean =
    meanVector.repeat(
      0,
      n
    );


  // ----------------------------------------------------
  // CENTER DATA
  // ----------------------------------------------------

  var centered =
    X.subtract(
      repeatedMean
    );


  // ----------------------------------------------------
  // SAMPLE COVARIANCE MATRIX
  //
  // COV =
  //
  //     X' X
  //    -------
  //     n - 1
  //
  // ----------------------------------------------------

  var covariance =
    centered

      .matrixTranspose()

      .matrixMultiply(
        centered
      )

      .divide(
        ee.Number(
          n
        ).subtract(
          1
        )
      );


  // ----------------------------------------------------
  // RAW DETERMINANT
  // ----------------------------------------------------

  var rawDeterminant =
    covariance
      .matrixDeterminant();


  // ----------------------------------------------------
  // CREATE 9 x 9 IDENTITY MATRIX
  // ----------------------------------------------------

  var identity =
    ee.Array.identity(
      MLC_BAND_COUNT
    );


  // ----------------------------------------------------
  // REGULARIZED COVARIANCE
  // ----------------------------------------------------

  var covarianceRegularized =
    covariance.add(

      identity.multiply(
        MLC_REGULARIZATION
      )

    );


  // ----------------------------------------------------
  // REGULARIZED DETERMINANT
  // ----------------------------------------------------

  var regularizedDeterminant =
    covarianceRegularized
      .matrixDeterminant();


  // ----------------------------------------------------
  // INVERSE
  // ----------------------------------------------------

  var inverseCovariance =
    covarianceRegularized
      .matrixInverse();


  // ----------------------------------------------------
  // INVERSE QA
  //
  // COV x COV^-1 should approximately equal identity.
  //
  // ----------------------------------------------------

  var inverseCheck =
    covarianceRegularized

      .matrixMultiply(
        inverseCovariance
      );


  // ----------------------------------------------------
  // DIAGONAL VARIANCES
  // ----------------------------------------------------

  var covarianceDiagonal =
    covariance
      .matrixDiagonal();


  // ----------------------------------------------------
  // STORE EVERYTHING
  // ----------------------------------------------------

  return ee.Dictionary({

    class_id:
      classId,

    class_name:
      className,

    n:
      n,

    mean:
      meanVector,

    covariance:
      covariance,

    covariance_diagonal:
      covarianceDiagonal,

    raw_determinant:
      rawDeterminant,

    regularized_covariance:
      covarianceRegularized,

    regularized_determinant:
      regularizedDeterminant,

    inverse_covariance:
      inverseCovariance,

    inverse_check:
      inverseCheck

  });

}


