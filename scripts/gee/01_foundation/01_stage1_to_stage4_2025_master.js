function geometryToFeatures(
  geometryLayer,
  classId,
  className
) {

  var geometries = ee.List(
    geometryLayer.geometries()
  );


  var features = geometries.map(
    function(g) {

      return ee.Feature(
        ee.Geometry(g),
        {
          class_id: classId,
          class_name: className,
          year: 2025,
          dataset: 'training'
        }
      );

    }
  );


  return ee.FeatureCollection(
    features
  );

}


