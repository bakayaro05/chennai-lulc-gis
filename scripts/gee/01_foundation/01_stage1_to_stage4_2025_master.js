// 4. LANDSAT 5 PREPROCESSING
// ======================================================
//
// QA_PIXEL:
//
// bit 0 = fill
// bit 1 = dilated cloud
// bit 3 = cloud
// bit 4 = cloud shadow
// bit 5 = snow
//
// Landsat 5:
//
// SR_B1 = blue
// SR_B2 = green
// SR_B3 = red
// SR_B4 = NIR
// SR_B5 = SWIR1
// SR_B7 = SWIR2
//
// Surface reflectance scaling:
//
// DN * 0.0000275 - 0.2
//
// ======================================================

function preprocessL5(image) {

  var qa = image.select('QA_PIXEL');

  var radsat = image.select('QA_RADSAT');


  // ----------------------------------------------------
  // Clear pixel mask
  // ----------------------------------------------------

  var clearMask = qa.bitwiseAnd(1 << 0).eq(0)

    .and(
      qa.bitwiseAnd(1 << 1).eq(0)
    )

    .and(
      qa.bitwiseAnd(1 << 3).eq(0)
    )

    .and(
      qa.bitwiseAnd(1 << 4).eq(0)
    )

    .and(
      qa.bitwiseAnd(1 << 5).eq(0)
    )

    .and(
      radsat.eq(0)
    );


  // ----------------------------------------------------
  // Select + rename + scale
  // ----------------------------------------------------

  var optical = image

    .select(

      [
        'SR_B1',
        'SR_B2',
        'SR_B3',
        'SR_B4',
        'SR_B5',
        'SR_B7'
      ],

      [
        'blue',
        'green',
        'red',
        'nir',
        'swir1',
        'swir2'
      ]

    )

    .multiply(0.0000275)

    .add(-0.2);


  return optical

    .updateMask(clearMask)

    .copyProperties(

      image,

      [
        'system:time_start',
        'LANDSAT_PRODUCT_ID',
        'SPACECRAFT_ID'
      ]

    );

}



