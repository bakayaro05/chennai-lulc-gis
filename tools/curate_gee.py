#!/usr/bin/env python3
"""Non-destructive curation for the Chennai LULC GEE repository.

Requires existing archive/gee-original/, docs/SCRIPT_INDEX.csv, and
this script's sibling gee_curated_selection.csv. Uses only Python stdlib.

Usage from repository root:
  python tools/curate_gee.py --plan
  python tools/curate_gee.py --apply
  python tools/curate_gee.py --verify

Copies exact archived bytes into a curated folder. Never evaluates GEE code.
"""
