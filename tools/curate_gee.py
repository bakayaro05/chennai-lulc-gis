VALID_FOLDERS = {
    '01_foundation', '02_2015_mlc', '03_2010_provisional',
    '04_four_class', '05_fusion', '06_generalisability', '07_map_exports'
}
SECRET_PATTERNS = (
    re.compile(rb'-----BEGIN (?:RSA |EC |OPENSSH |DSA )?PRIVATE KEY-----'),
    re.compile(rb'AIza[0-9A-Za-z_-]{30,}'),
    re.compile(rb'github_pat_[0-9A-Za-z_]{25,}'),
    re.compile(rb'ghp_[0-9A-Za-z]{20,}'),
)


def read_csv(path: Path) -> list[dict[str, str]]:
    with path.open('r', encoding='utf-8-sig', newline='') as fh:
        return list(csv.DictReader(fh))


def sha256(data: bytes) -> str:
    return hashlib.sha256(data).hexdigest()


def dest_name(path: str) -> str:
    base = PurePosixPath(path).name
    if not base.lower().endswith('.js'):
        base += '.js'
    return re.sub(r'_+', '_', re.sub(r'[^\w.\-]', '_', base, flags=re.ASCII))


def safe_archive_path(root: Path, relative: str) -> Path:
    parts = PurePosixPath(relative)
    if parts.is_absolute() or '..' in parts.parts or not relative or '\\' in relative:
        raise ValueError(f'Unsafe archive path in inventory: {relative!r}')
    target = root.joinpath(*parts.parts)
    if target.is_symlink():
        raise ValueError(f'Symbolic-link source not supported: {relative}')
    if not target.resolve().is_relative_to(root.resolve()):
        raise ValueError(f'Archive path escapes root: {relative}')
    return target


def check_preflight(repo: Path, selection_csv: Path):
    archive = repo / 'archive' / 'gee-original'
    master_csv = repo / 'docs' / 'SCRIPT_INDEX.csv'
    if not archive.is_dir() or not master_csv.is_file():
        raise ValueError('Run from chennai-lulc-gis root; archive and docs/SCRIPT_INDEX.csv required.')
    index = read_csv(master_csv)
    if len(index) != EXPECTED_UPSTREAM_FILES:
        raise ValueError(f'Expected {EXPECTED_UPSTREAM_FILES} source inventory entries; found {len(index)}.')
    entries = {}
    for row in index:
        rel = row['relative_path']
        if rel in entries:
            raise ValueError(f'Duplicate inventory path: {rel}')
        entries[rel] = row
    actual = {p.relative_to(archive).as_posix() for p in archive.rglob('*') if p.is_file()}
    expected = set(entries)
    if actual != expected:
        raise ValueError(f'Archive inventory mismatch: {len(actual)} actual; '
                         f'missing={sorted(expected-actual)[:6]}; extra={sorted(actual-expected)[:6]}')
    checked = {}
    secrets = []
    for rel, row in entries.items():
        src = safe_archive_path(archive, rel)
        data = src.read_bytes()
        if len(data) != int(row['bytes']) or sha256(data) != row['sha256']:
            raise ValueError(f'ARCHIVE CHECKSUM/SIZE MISMATCH: {rel}. Do not proceed.')
        if any(p.search(data) for p in SECRET_PATTERNS):
            secrets.append(rel)
        checked[rel] = data
    if secrets:
        raise ValueError('Possible credentials in archived files. Review privately before continuing: '
                         + ', '.join(secrets[:12]))
    selections = read_csv(selection_csv)
    if len(selections) != EXPECTED_CURATED_FILES:
        raise ValueError(f'Expected {EXPECTED_CURATED_FILES} curated entries; found {len(selections)}.')
    selected = []
    seen_src, seen_dest = set(), set()
    for row in selections:
        rel = row['source_path']
        if rel in seen_src or rel not in checked:
            raise ValueError(f'Duplicate or missing curated source: {rel}')
        if row['category'] not in VALID_FOLDERS:
            raise ValueError(f'Unknown curated category for {rel}: {row["category"]}')
        if not row['description'].strip():
            raise ValueError(f'No description for {rel}')
        dest_rel = f'{row["category"]}/{dest_name(rel)}'
        if dest_rel in seen_dest:
            raise ValueError(f'Two source files collide on curated path: {dest_rel}')
        seen_src.add(rel)
        seen_dest.add(dest_rel)
        selected.append((row, dest_rel, checked[rel], entries[rel]))
    return selected, len(index)


def csv_output(selected) -> bytes:
    buf = io.StringIO(newline='')
    writer = csv.writer(buf)
    writer.writerow(('source_path', 'curated_path', 'decision', 'execution', 'sha256',
                     'bytes', 'description', 'provenance'))
    for row, out, data, idx in selected:
        writer.writerow((row['source_path'], 'scripts/gee/' + out, row['decision'],
                         row['execution'], idx['sha256'], len(data), row['description'],
                         'byte-identical copy from archive/gee-original/'))
    return buf.getvalue().encode('utf-8')


