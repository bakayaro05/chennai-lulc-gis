def known_generated_previous(repo: Path, target: Path) -> bool:
    key = target.relative_to(repo).as_posix()
    known = PREVIOUS_GENERATED_SHA256.get(key)
    return bool(known and sha256(target.read_bytes()) == known)


def legacy_status(repo: Path) -> list[str]:
    results = []
    for folder in LEGACY_DIRS:
        p = repo / 'scripts' / 'gee' / folder
        if p.exists():
            if not p.is_dir():
                results.append(f'LEGACY name is not a directory: {folder}')
            elif not any(p.iterdir()):
                results.append(f'LEGACY empty folder (safe to rmdir manually): {folder}')
            else:
                results.append(f'LEGACY NONEMPTY folder (preserve and inspect): {folder}')
    return results


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    group = parser.add_mutually_exclusive_group(required=True)
    group.add_argument('--plan', action='store_true', help='Verify all files and print only; no writes')
    group.add_argument('--apply', action='store_true', help='Verify and create immutable curated copies and documentation')
    group.add_argument('--verify', action='store_true', help='Re-verify curated outputs and docs; no writes')
    args = parser.parse_args()
    repo = Path.cwd().resolve()
    selection_csv = Path(__file__).resolve().with_name('gee_curated_selection.csv')
    try:
        selected, originals = check_preflight(repo, selection_csv)
        targets = {}
        for row, rel, data, _ in selected:
            targets[repo / 'scripts' / 'gee' / rel] = data
        targets[repo / 'docs' / 'CURATED_GEE_MANIFEST.csv'] = csv_output(selected)
        targets[repo / 'docs' / 'CURATED_GEE_AUDIT.md'] = audit_output(selected, originals)
        targets[repo / 'scripts' / 'gee' / 'INDEX.md'] = index_output(selected, originals)
        readme_path = repo / 'scripts' / 'gee' / 'README.md'
        targets[readme_path] = curated_readme_output()
        targets[repo / 'scripts' / 'gee' / 'EXECUTION_ORDER.md'] = execution_output()
        collisions = [str(p.relative_to(repo)) for p, data in targets.items()
                      if p.exists() and p.read_bytes() != data
                      and not (p == readme_path and p.read_bytes() == STARTER_README)
                      and not known_generated_previous(repo, p)]
        if collisions:
            raise ValueError('Pre-existing files differ: '+', '.join(collisions[:12])+
                             '. Nothing overwritten. Review first.')
        if args.verify:
            absent = [str(p.relative_to(repo)) for p in targets if not p.is_file()]
            if absent:
                raise ValueError('Curated outputs not yet generated: '+', '.join(absent[:12]))
        elif args.apply:
            for p, data in targets.items():
                p.parent.mkdir(parents=True, exist_ok=True)
                if (not p.exists() or (p == readme_path and p.read_bytes() == STARTER_README)
                    or known_generated_previous(repo, p)):
                    p.write_bytes(data)
            for p, data in targets.items():
                if p.read_bytes() != data:
                    raise ValueError(f'Post-copy mismatch: {p.relative_to(repo)}')
        action = 'PLAN PASSED' if args.plan else ('VERIFIED' if args.verify else 'CREATED AND VERIFIED')
        print(f'{action}: {originals} original files SHA-256 checked; '
              f'{len(selected)} curated exact-byte .js copies; 5 documentation outputs.')
        if args.plan:
            for category, n in sorted(Counter(x[0]['category'] for x in selected).items()):
                print(' ', category, n)
            print('No files changed. Run --apply only after reviewing the selection CSV.')
        else:
            print('Original archive unchanged. Review: scripts/gee/INDEX.md and docs/CURATED_GEE_AUDIT.md')
        for item in legacy_status(repo):
            print(' ', item)
        return 0
    except (OSError, KeyError, ValueError) as exc:
        print('STOPPED SAFELY:', exc, file=sys.stderr)
        return 1


if __name__ == '__main__':
    sys.exit(main())
